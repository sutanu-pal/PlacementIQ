from __future__ import annotations

from typing import TYPE_CHECKING, Any, Dict, List, Optional
from sqlalchemy import Boolean, Float, ForeignKey, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship
from sqlalchemy.types import JSON

from app.models.base import Base, TimestampMixin, UUIDMixin

if TYPE_CHECKING:
    from app.models.user import User
    from app.models.resume import Resume


class Job(Base, UUIDMixin, TimestampMixin):
    __tablename__ = "jobs"

    title: Mapped[str] = mapped_column(String(255), nullable=False, index=True)
    company: Mapped[str] = mapped_column(String(255), nullable=False, index=True)
    description: Mapped[str] = mapped_column(Text, nullable=False)
    responsibilities: Mapped[List[str]] = mapped_column(JSON, nullable=False, default=list)
    eligibility_criteria: Mapped[Dict[str, Any]] = mapped_column(JSON, nullable=False, default=dict)
    
    # Skills stored as JSON arrays of strings for fast filtering / serialization
    required_skills: Mapped[List[str]] = mapped_column(JSON, nullable=False, default=list)
    preferred_skills: Mapped[List[str]] = mapped_column(JSON, nullable=False, default=list)

    experience_level: Mapped[str] = mapped_column(String(50), nullable=False, default="Fresher / Entry Level", index=True)
    location: Mapped[str] = mapped_column(String(100), nullable=False, default="Bengaluru", index=True)
    employment_type: Mapped[str] = mapped_column(String(50), nullable=False, default="Full-time", index=True)
    salary_range: Mapped[str] = mapped_column(String(100), nullable=False, default="")
    is_active: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True, index=True)

    # Clearly label synthetic test/sample jobs to ensure academic honesty
    is_synthetic: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True)

    # Cached 384-dimensional embedding generated by all-MiniLM-L6-v2
    embedding: Mapped[Optional[List[float]]] = mapped_column(JSON, nullable=True)

    # Relationships
    skills: Mapped[List["JobSkill"]] = relationship(
        "JobSkill",
        back_populates="job",
        cascade="all, delete-orphan",
        order_by="JobSkill.skill_name",
    )
    matches: Mapped[List["JobMatch"]] = relationship(
        "JobMatch",
        back_populates="job",
        cascade="all, delete-orphan",
        order_by="desc(JobMatch.created_at)",
    )

    def __repr__(self) -> str:
        return f"<Job id={self.id} title={self.title} company={self.company}>"


class JobSkill(Base, UUIDMixin, TimestampMixin):
    __tablename__ = "job_skills"

    job_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("jobs.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    skill_name: Mapped[str] = mapped_column(String(100), nullable=False, index=True)
    is_required: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True)
    category: Mapped[str] = mapped_column(String(50), nullable=False, default="Technical")

    # Relationship
    job: Mapped["Job"] = relationship("Job", back_populates="skills")

    def __repr__(self) -> str:
        return f"<JobSkill job={self.job_id} skill={self.skill_name} req={self.is_required}>"


class JobMatch(Base, UUIDMixin, TimestampMixin):
    __tablename__ = "job_matches"

    user_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    job_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("jobs.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    resume_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("resumes.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    resume_version: Mapped[int] = mapped_column(Integer, nullable=False, default=1)

    # Scores (0.0 to 100.0)
    match_score: Mapped[float] = mapped_column(Float, nullable=False, default=0.0, index=True)
    skill_score: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
    semantic_score: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
    project_score: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)

    # Detailed Explainability Data
    matched_skills: Mapped[List[str]] = mapped_column(JSON, nullable=False, default=list)
    missing_required_skills: Mapped[List[str]] = mapped_column(JSON, nullable=False, default=list)
    missing_preferred_skills: Mapped[List[str]] = mapped_column(JSON, nullable=False, default=list)
    project_relevance: Mapped[Dict[str, Any]] = mapped_column(JSON, nullable=False, default=dict)
    score_breakdown: Mapped[Dict[str, Any]] = mapped_column(JSON, nullable=False, default=dict)
    explanations: Mapped[List[str]] = mapped_column(JSON, nullable=False, default=list)
    recommendations: Mapped[List[str]] = mapped_column(JSON, nullable=False, default=list)

    algorithm_version: Mapped[str] = mapped_column(String(50), nullable=False, default="v1.0-weighted")

    # Relationships
    user: Mapped["User"] = relationship("User", back_populates="job_matches")
    job: Mapped["Job"] = relationship("Job", back_populates="matches")
    resume: Mapped["Resume"] = relationship("Resume", back_populates="job_matches")

    def __repr__(self) -> str:
        return f"<JobMatch id={self.id} user={self.user_id} job={self.job_id} score={self.match_score}>"
